import type { AIReadingRequest } from "@/app/api/ai-reading/route";

type PromptConfig = {
  /** Builds the system prompt for a specific tool. */
  systemPrompt: (req: AIReadingRequest) => string;
  /** Builds the user-facing message sent alongside the system prompt. */
  userMessage: (req: AIReadingRequest) => string;
};

/** Shared closing rules appended to every tool prompt. */
const SHARED_RULES = `## Important rules
- Write in fluent, natural English. No Chinese characters unless you also explain them.
- Keep the total response to 250-350 words — substantial but scannable.
- Use paragraph breaks for readability.
- If the data seems contradictory, acknowledge the complexity — real people are layered too.
- NEVER say "you will" or "you are destined to." Say "you may find that..." or "this pattern often suggests..."
- NEVER reference "the AI" or "the model" or break character.
- NEVER give medical, legal, or financial advice. This is cultural exploration and self-discovery.`;

function formatName(req: AIReadingRequest): string {
  return req.input.name.trim() || "the seeker";
}

function formatQuestion(req: AIReadingRequest): string {
  return req.input.question.trim() || "life direction";
}

function formatSections(req: AIReadingRequest): string {
  return req.reading.sections
    .map((s) => `- **${s.label}**: ${s.value}`)
    .join("\n");
}

function formatChart(req: AIReadingRequest): string {
  return req.reading.chart
    .map((d) => `${d.name} (${d.value})`)
    .join(", ");
}

